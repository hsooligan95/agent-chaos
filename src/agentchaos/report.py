"""Report generation: Markdown summary + full JSON detail."""

from __future__ import annotations

import json
from pathlib import Path

from .scoring import silent_failure_rate

OUTCOME_LABEL = {
    "success": "success",
    "recovered": "recovered",
    "failed_loudly": "FAILED LOUDLY",
    "failed_silently": "FAILED SILENTLY",
}


def build_report(rows: list[dict]) -> dict:
    off_rows = [r for r in rows if r["mode"] == "off"]
    on_rows = [r for r in rows if r["mode"] == "on"]
    return {
        "headline": {
            "silent_failure_rate_defenses_off": silent_failure_rate(off_rows),
            "silent_failure_rate_defenses_on": silent_failure_rate(on_rows),
            "fault_scenarios": sum(1 for r in off_rows if r["fault_injected"]),
        },
        "rows": rows,
    }


def render_markdown(report: dict) -> str:
    h = report["headline"]
    lines = [
        "# AgentChaos results",
        "",
        "Generated by `python -m agentchaos run`. Deterministic: the same",
        "command always produces this report. Token counts are simulated",
        "accounting (fixed per call/step), not billed usage.",
        "",
        "## Headline",
        "",
        f"- Silent-failure rate, defenses OFF: **{h['silent_failure_rate_defenses_off']:.0%}** "
        f"of {h['fault_scenarios']} fault scenarios",
        f"- Silent-failure rate, defenses ON: **{h['silent_failure_rate_defenses_on']:.0%}** "
        f"of {h['fault_scenarios']} fault scenarios",
        "",
        "## Scenario matrix",
        "",
        "| Scenario | Mode | Fault injected | Detected (step) | Outcome | Answer correct | Tokens | Cost (sim.) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in report["rows"]:
        detected = (
            f"yes (step {r['detection_step']})" if r["detected"] else "no"
        )
        lines.append(
            f"| {r['scenario']} | {r['mode']} | {r['fault']} | {detected} | "
            f"{OUTCOME_LABEL[r['outcome']]} | {'yes' if r['answer_correct'] else 'no'} | "
            f"{r['tokens']} | ${r['cost_usd']:.4f} |"
        )
    lines += [
        "",
        "Outcome key: **recovered** = correct answer despite the fault; "
        "**FAILED LOUDLY** = agent abstained / surfaced the problem; "
        "**FAILED SILENTLY** = wrong answer delivered as if correct.",
        "",
    ]
    return "\n".join(lines)


def write_reports(report: dict, out_dir: str | Path) -> tuple[Path, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    md_path = out / "report.md"
    json_path = out / "report.json"
    md_path.write_text(render_markdown(report), encoding="utf-8")
    json_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return md_path, json_path
